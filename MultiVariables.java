public class MultiVariables {
    public static void main(String[] args){
        
        
        // Declare Many Variables

            int x = 5;
            int y = 6;
            int z = 50;
            System.out.println(x + y + z); // 61

        // Declare Many Variables in One Line

            int a = 5, b = 6, c = 50;
            System.out.println(a + b + c); // 61

        // One Value to Multiple Variables

            int p, q, r;
            p = q = r = 50;
            System.out.println(p + q + r); // 150
    }
}
